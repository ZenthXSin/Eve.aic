import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const modulePath = process.env.EVE_PLAYWRIGHT_MODULE;
if (!modulePath) throw new Error('需要 EVE_PLAYWRIGHT_MODULE');
const { chromium } = await import(pathToFileURL(modulePath).href);
const browser = await chromium.launch({ executablePath:process.env.EVE_TEST_BROWSER, headless:true, args:['--no-sandbox'] });
const page = await browser.newPage({ viewport:{width:1400,height:1000} });
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{ if(message.type()==='error' && message.text().startsWith('EVE_WEB_CHAT_CLIENT_ERROR')) errors.push(message.text()); });
try {
  await page.goto(process.env.EVE_WEB_TEST_URL);
  const login=async()=>{
    await page.locator('#access-token').fill(process.env.EVE_WEB_TEST_TOKEN);
    await page.locator('#login-submit').click();
    await page.locator('#chat-view').waitFor({state:'visible'});
    await page.waitForFunction(()=>!document.querySelector('#chat-send').disabled);
  };
  await login();
  assert.equal(await page.locator('#chat-view .count-pill').textContent(),'主人');
  await page.locator('#chat-input').fill('你好 Eve\n保留换行');
  await page.locator('#chat-send').click();
  await page.locator('.chat-message.assistant').filter({hasText:'网页回复：你好 Eve\n保留换行'}).waitFor();
  await page.reload();
  await page.locator('#login-view').waitFor({state:'visible'});
  assert.equal(await page.locator('#access-token').inputValue(),'');
  assert.equal(await page.evaluate(token=>JSON.stringify(Object.values(sessionStorage)).includes(token),process.env.EVE_WEB_TEST_TOKEN),false);
  await login();
  await page.locator('.chat-message.assistant').filter({hasText:'网页回复：你好 Eve\n保留换行'}).waitFor();
  await page.locator('#chat-new').click();
  await page.waitForFunction(()=>!document.querySelector('#chat-send').disabled);
  await page.waitForFunction(()=>!document.querySelector('#chat-messages').textContent.includes('你好 Eve'));
  await page.locator('#chat-input').fill('<img src=x onerror="window.eveInjected=true">');
  await page.locator('#chat-send').click();
  await page.locator('.chat-message.assistant').filter({hasText:'网页回复：<img src=x onerror="window.eveInjected=true">'}).waitFor();
  assert.equal(await page.locator('#chat-messages img').count(),0);
  assert.equal(await page.evaluate(()=>window.eveInjected),undefined);
  await page.waitForFunction(()=>!document.querySelector('#chat-send').disabled);
  await page.locator('#chat-input').fill('等待取消');
  await page.locator('#chat-send').click();
  await page.waitForFunction(()=>!document.querySelector('#chat-cancel').disabled);
  await page.locator('#chat-cancel').click();
  await page.waitForFunction(()=>document.querySelector('#chat-status').textContent==='已停止');
  await page.waitForFunction(()=>!document.querySelector('#chat-send').disabled);
  assert.match(await page.locator('#chat-messages').textContent(),/已停止本轮/);
  assert.equal(await page.locator('.chat-message.notice').count(),1,'同一取消结果只显示一次');
  await page.screenshot({path:join(tmpdir(),'eve-web-chat-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:join(tmpdir(),'eve-web-chat-mobile.png'),fullPage:true});
  await page.locator('#logout-button').click();
  await page.locator('#login-view').waitFor({state:'visible'});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({owner:true,dialogue:true,reload:true,separate_conversations:true,cancel:true,escaped_text:true,mobile:true}));
} catch(error) {
  console.error(JSON.stringify({errors,status:await page.locator('#chat-status').textContent(),error:await page.locator('#chat-error').textContent(),pending:await page.evaluate(()=>Object.entries(sessionStorage).filter(([k])=>k.includes('pending')).map(([k,v])=>[k,JSON.parse(v).request_id]))}));
  await page.screenshot({path:join(tmpdir(),'eve-web-chat-failed.png'),fullPage:true});
  throw error;
} finally { await browser.close(); }
